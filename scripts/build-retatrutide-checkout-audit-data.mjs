import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

import {
  buildPaymentProviderRollup,
  enrichPaymentProviders,
} from "./payment-provider-taxonomy.mjs";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const INPUT = path.join(ROOT, ".context/noli-checkout-scan-2026-07-27.json");
const OUTPUT = path.join(
  ROOT,
  "biologix-strategy-board/research/retatrutide-checkout-audit-data.js"
);

const source = JSON.parse(await readFile(INPUT, "utf8"));
const audits = Object.fromEntries(
  Object.entries(source.byDomain || {}).map(([domain, profile]) => {
    const providerSignals = enrichPaymentProviders(profile.payment, {
      capturedAt: profile.payment?.evidence?.observedAt || source.meta?.scanDate,
    });
    return [
      domain,
      {
      ...profile,
      status: "complete",
      statusEvidence: profile.status,
      pagesCrawled: Array.isArray(profile.pagesCrawled)
        ? profile.pagesCrawled.length
        : Number(profile.pagesCrawled || 0),
      pageUrls: Array.isArray(profile.pagesCrawled) ? profile.pagesCrawled : [],
      design: profile.uiUx || null,
      payment: {
        ...profile.payment,
        providerSignals,
        note:
          "Public code and runtime can identify provider-branded integrations. Active cart evidence is stronger than an installed plugin or logo, but it does not prove a successful transaction, written underwriting, the merchant's contractual processor/ISO, merchant of record, downstream processor behind a multi-processor gateway, or the acquirer and sponsor bank.",
      },
      auditType: "Anonymous Reta storefront and checkout scan"
    },
    ];
  })
);

const paymentProviderRollup = buildPaymentProviderRollup(audits);
const payload = {
  generatedAt: source.meta?.generatedAt || new Date().toISOString(),
  methodology: source.meta?.scope || null,
  evidenceRules: [
    ...(source.meta?.evidenceRules || []),
    "Provider names and roles are extracted from public script, plugin, API, and rendered checkout identifiers. They are not erased merely because the downstream acquirer is unknown.",
    "A provider-branded method returned for the tested Reta cart is reported as active cart evidence. It is not reported as a completed transaction or durable underwriting approval.",
  ],
  stats: {
    ...(source.meta || {}),
    paymentProviderRollup,
  },
  audits
};

const banner =
  "/* Generated by scripts/build-retatrutide-checkout-audit-data.mjs. Do not edit by hand. */\n";
await writeFile(
  OUTPUT,
  `${banner}window.NOLI_RETATRUTIDE_CHECKOUT_AUDITS = ${JSON.stringify(payload)};\n`,
  "utf8"
);

console.log(
  `Wrote ${Object.keys(audits).length} checkout profiles to ${path.relative(ROOT, OUTPUT)}`
);
