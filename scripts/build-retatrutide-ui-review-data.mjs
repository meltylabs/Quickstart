import { access, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const inputs = [
  path.join(ROOT, ".context/noli-ui-score-wave-a-2026-07-27.json"),
  path.join(ROOT, ".context/noli-ui-score-wave-b-2026-07-27.json"),
  path.join(ROOT, ".context/noli-ui-score-wave-c-2026-07-27.json")
];
const OUTPUT = path.join(
  ROOT,
  "biologix-strategy-board/research/retatrutide-ui-review-data.js"
);

const sources = [];
for (const input of inputs) {
  try {
    await access(input);
    sources.push({
      path: input,
      data: JSON.parse(await readFile(input, "utf8"))
    });
  } catch (error) {
    if (error.code !== "ENOENT") throw error;
  }
}
if (!sources.length) throw new Error("No completed UI review wave was found.");

const audits = {};
const firstLoadStates = {};
const confidenceCounts = {};
let latestTimestamp = 0;
let scoredDomains = 0;
let unscoredDomains = 0;

for (const source of sources) {
  const sourceRecords = source.data.byDomain || source.data;
  for (const [domain, review] of Object.entries(sourceRecords || {})) {
    if (!review || typeof review !== "object" || !review.domain) continue;
    const checkedAt =
      review.checkedAt ||
      review.capturedAt ||
      source.data.meta?.generatedAt ||
      null;
    latestTimestamp = Math.max(latestTimestamp, Date.parse(checkedAt || "") || 0);
    const firstLoadState =
      review.firstLoadState ||
      review.accessStatus ||
      (review.comparable === true ? "open-product" : "unknown");
    const confidence =
      review.confidence ||
      (review.comparable === true ? "high" : "low");
    const scores = review.scores || {};
    const normalizedScores = {
      mobileUsability: scores.mobileUsability ?? null,
      visualPolish: scores.visualPolish ?? null,
      productClarity: scores.productClarity ?? null,
      trustPresentation: scores.trustPresentation ?? null,
      conversionUx: scores.conversionUx ?? scores.conversionUX ?? null,
      performance: scores.performance ?? null,
      overall: scores.overall ?? review.overall ?? null
    };
    if (Number.isFinite(normalizedScores.overall)) scoredDomains += 1;
    else unscoredDomains += 1;
    firstLoadStates[firstLoadState] = (firstLoadStates[firstLoadState] || 0) + 1;
    confidenceCounts[confidence] = (confidenceCounts[confidence] || 0) + 1;

    audits[domain] = {
      design: {
        ...normalizedScores,
        firstLoadState,
        firstLoadScope: review.firstLoadScope || null,
        reasons: review.reasons || [],
        observedUrl:
          review.scoredUrl ||
          review.productUrl ||
          review.homepageUrl ||
          null,
        checkedAt,
        confidence,
        screenshotReviewed:
          review.screenshotReviewed === true ||
          Boolean(review.screenshots) ||
          Boolean(review.evidence?.screenshots),
        scoringBasis:
          "Screenshot-reviewed public UI at 390x844 mobile and 1440x900 desktop. Gates and challenges remain first-load friction and were not crossed.",
        disclaimer:
          review.disclaimer ||
          "UI score only. It is not evidence of product quality, safety, legality, regulatory compliance, processor durability, revenue, or business scale."
      },
      uiReview: {
        waveIndex: review.waveIndex || null,
        sourceRetailStatus: review.sourceRetailStatus || null,
        targetSource: review.targetSource || null,
        firstLoadState,
        scoredUrl:
          review.scoredUrl ||
          review.productUrl ||
          review.homepageUrl ||
          null
      },
      evidence: (review.evidence?.urls || review.evidenceUrls || [])
        .filter((url) => /^https?:\/\//i.test(url))
        .map((url) => ({
          field: "design.screenshotReview",
          url,
          capturedAt: checkedAt,
          confidence
        })),
      errors:
        review.accessErrors ||
        (review.comparable === false ? review.reasons || [] : [])
    };
  }
}

const payload = {
  generatedAt: latestTimestamp
    ? new Date(latestTimestamp).toISOString()
    : new Date().toISOString(),
  methodology:
    "Direct screenshot-reviewed public UI scoring. No accounts, gates, forms, carts, checkout, personal data, payment, transaction, or evasion.",
  stats: {
    reviewedDomains: Object.keys(audits).length,
    wavesIncluded: sources.length,
    scoredDomains,
    unscoredDomains,
    firstLoadStates,
    confidenceCounts
  },
  audits
};

const banner =
  "/* Generated by scripts/build-retatrutide-ui-review-data.mjs. Do not edit by hand. */\n";
await writeFile(
  OUTPUT,
  `${banner}window.NOLI_RETATRUTIDE_UI_REVIEWS = ${JSON.stringify(payload)};\n`,
  "utf8"
);

console.log(
  `Wrote ${Object.keys(audits).length} screenshot-reviewed UI profiles from ${sources.length} wave(s).`
);
