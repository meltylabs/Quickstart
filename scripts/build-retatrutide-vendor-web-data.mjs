import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import vm from "node:vm";
import { fileURLToPath } from "node:url";

import { enrichPaymentProviders } from "./payment-provider-taxonomy.mjs";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const INPUT = path.join(
  ROOT,
  "biologix-strategy-board/research/retatrutide-vendor-audit-data.js"
);
const OUTPUT = path.join(
  ROOT,
  "biologix-strategy-board/research/retatrutide-vendor-audit-web-data.js"
);

const context = { window: {} };
vm.runInNewContext(await readFile(INPUT, "utf8"), context, { filename: INPUT });
const source = context.window.NOLI_RETATRUTIDE_VENDOR_AUDITS;
if (!source?.audits) throw new Error("Full vendor audit payload was not found.");

const arrayLimits = {
  pageUrls: 8,
  detected: 4,
  plugins: 10,
  serverHeaders: 4,
  productUrls: 6,
  contentUrls: 4,
  strengths: 8,
  forms: 4,
  prices: 8,
  positioning: 6,
  offers: 6,
  tracking: 10,
  coaLinks: 6,
  reviewProviders: 4,
  displayedReviewCounts: 4,
  displayedRatings: 4,
  shipping: 4,
  returns: 4,
  contactUrls: 4,
  policyUrls: 6,
  visibleMethods: 8,
  checkoutIntegration: 8,
  gatewayPsp: 6,
  processorIso: 4,
  acquirerSponsorBank: 4,
  providerSignals: 12,
  roles: 5,
  researchOnly: 6,
  humanUseOrOutcome: 6,
  all: 6,
  claims: 6,
  reasons: 5,
  errors: 4
};

function compactValue(value, key = "") {
  if (value == null || typeof value === "boolean" || typeof value === "number") return value;
  if (typeof value === "string") {
    return value.length > 220 ? `${value.slice(0, 217)}...` : value;
  }
  if (Array.isArray(value)) {
    const limit = arrayLimits[key] ?? 12;
    return value.slice(0, limit).map((item) => compactValue(item, key));
  }
  if (typeof value !== "object") return value;

  return Object.fromEntries(
    Object.entries(value)
      .filter(([nestedKey]) =>
        !["evidenceIds", "contactEmails", "publicId"].includes(nestedKey)
      )
      .map(([nestedKey, nestedValue]) => [
        nestedKey,
        compactValue(nestedValue, nestedKey)
      ])
  );
}

const confidenceRank = { high: 0, medium: 1, low: 2 };
const fieldRank = (field = "") => {
  if (/^(reta|payment|sourcing)/.test(field)) return 0;
  if (/^(pricing|marketing|trust|claims)/.test(field)) return 1;
  if (/^(operations|platform|tracking)/.test(field)) return 2;
  return 3;
};

function compactEvidence(evidence = []) {
  const seen = new Set();
  return [...evidence]
    .filter((item) => item?.url)
    .sort((left, right) =>
      fieldRank(left.field) - fieldRank(right.field) ||
      (confidenceRank[left.confidence] ?? 3) - (confidenceRank[right.confidence] ?? 3)
    )
    .filter((item) => {
      const key = `${item.field || ""}|${item.url}`;
      if (seen.has(key)) return false;
      seen.add(key);
      return true;
    })
    .slice(0, 10)
    .map((item) => ({
      field: item.field || null,
      url: item.url,
      capturedAt: item.capturedAt || null,
      confidence: item.confidence || null
    }));
}

const audits = Object.fromEntries(
  Object.entries(source.audits).map(([domain, audit]) => {
    const evidenceById = new Map(
      (audit.evidence || []).filter((item) => item?.id).map((item) => [item.id, item])
    );
    const providerSignals =
      audit.payment?.providerSignals ||
      enrichPaymentProviders(audit.payment, {
        capturedAt: audit.capturedAt || source.generatedAt,
        evidenceById,
      });
    const enrichedAudit = {
      ...audit,
      payment: {
        ...(audit.payment || {}),
        providerSignals,
      },
    };
    return [
      domain,
      {
        ...compactValue(enrichedAudit),
        evidence: compactEvidence(audit.evidence),
        errors: compactValue(audit.errors, "errors")
      }
    ];
  })
);

const payload = {
  generatedAt: source.generatedAt,
  methodology: source.methodology,
  source: source.source,
  stats: {
    ...source.stats,
    webProjection: {
      profiles: Object.keys(audits).length,
      maximumEvidenceLinksPerProfile: 10,
      fullEvidenceRecords: Object.values(source.audits).reduce(
        (total, audit) => total + (audit.evidence?.length || 0),
        0
      ),
      fullArchive: "retatrutide-vendor-audit-data.js"
    }
  },
  audits
};

const banner =
  "/* Generated by scripts/build-retatrutide-vendor-web-data.mjs. The complete evidence ledger remains in retatrutide-vendor-audit-data.js. */\n";
await writeFile(
  OUTPUT,
  `${banner}window.NOLI_RETATRUTIDE_VENDOR_AUDITS = ${JSON.stringify(payload)};\n`,
  "utf8"
);

console.log(
  `Wrote ${Object.keys(audits).length} compact profiles to ${path.relative(ROOT, OUTPUT)}`
);
