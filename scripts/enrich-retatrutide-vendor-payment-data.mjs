import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import vm from "node:vm";
import { fileURLToPath } from "node:url";

import {
  buildPaymentProviderRollup,
  enrichPaymentProviders,
  PROVIDER_BOUNDARY,
} from "./payment-provider-taxonomy.mjs";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const inputArgument = process.argv.find((argument) => argument.startsWith("--input="));
const outputArgument = process.argv.find((argument) => argument.startsWith("--output="));
const INPUT = path.resolve(
  ROOT,
  inputArgument?.slice("--input=".length) ||
    "biologix-strategy-board/research/retatrutide-vendor-audit-data.js"
);
const OUTPUT = path.resolve(
  ROOT,
  outputArgument?.slice("--output=".length) ||
    "biologix-strategy-board/research/retatrutide-vendor-audit-data.js"
);

const context = { window: {} };
vm.runInNewContext(await readFile(INPUT, "utf8"), context, { filename: INPUT });
const source = context.window.NOLI_RETATRUTIDE_VENDOR_AUDITS;
if (!source?.audits) throw new Error("Vendor audit payload was not found.");

const audits = Object.fromEntries(
  Object.entries(source.audits).map(([domain, audit]) => {
    const evidenceById = new Map(
      (audit.evidence || []).filter((item) => item?.id).map((item) => [item.id, item])
    );
    const providerSignals = enrichPaymentProviders(audit.payment, {
      capturedAt: audit.capturedAt || source.generatedAt,
      evidenceById,
    });
    return [
      domain,
      {
        ...audit,
        payment: {
          ...(audit.payment || {}),
          providerSignals,
          evidenceBoundary: PROVIDER_BOUNDARY,
        },
      },
    ];
  })
);

const paymentProviderRollup = buildPaymentProviderRollup(audits);
const payload = {
  ...source,
  methodology: `${source.methodology || ""} Payment provider names and roles are normalized from public HTML, JavaScript, plugins, APIs, and checkout identifiers; downstream underwriting and acquiring remain separate.`.trim(),
  paymentEvidenceModel: {
    codeCanEstablish: [
      "Provider-branded script, plugin, SDK, API, or checkout identifier",
      "Whether a provider-branded method was returned for the tested anonymous Reta cart",
      "Provider's documented public role, such as gateway, PSP, processor, or pay-by-bank provider",
    ],
    codeDoesNotEstablish: [
      "Successful transaction",
      "Written underwriting approval for the exact catalog and claims",
      "Merchant of record",
      "Downstream processor when the named gateway supports multiple processors",
      "Acquirer or sponsor bank unless separately disclosed",
      "Durability, reserve terms, holds, chargeback rate, or termination risk",
    ],
    boundary: PROVIDER_BOUNDARY,
  },
  stats: {
    ...source.stats,
    paymentProviderRollup,
  },
  audits,
};

const banner =
  "/* Generated by scripts/audit-retatrutide-vendor-universe.mjs and enriched by scripts/enrich-retatrutide-vendor-payment-data.mjs. Do not edit by hand. */\n";
await writeFile(
  OUTPUT,
  `${banner}window.NOLI_RETATRUTIDE_VENDOR_AUDITS = ${JSON.stringify(payload)};\n`,
  "utf8"
);

console.log(
  `Enriched ${Object.keys(audits).length} profiles with ${Object.keys(paymentProviderRollup.providers).length} normalized payment-provider groups.`
);
